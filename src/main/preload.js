// Narrow bridge: the pages can ask for data, never for the key or for Node.
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('portal', {
  settings: () => ipcRenderer.invoke('settings:get'),
  saveKey: c => ipcRenderer.invoke('settings:saveKey', c),
  clearKey: () => ipcRenderer.invoke('settings:clearKey'),
  clearCache: () => ipcRenderer.invoke('cache:clear'),
  updateSettings: patch => ipcRenderer.invoke('settings:update', patch),
  testKey: () => ipcRenderer.invoke('settings:testKey'),
  appInfo: () => ipcRenderer.invoke('app:info'),
  exportData: () => ipcRenderer.invoke('data:export'),
  importData: () => ipcRenderer.invoke('data:import'),
  importApply: () => ipcRenderer.invoke('data:importApply'),
  environments: () => ipcRenderer.invoke('envs:list'),
  selectEnvironment: e => ipcRenderer.invoke('env:select', e),
  stack: (opts = {}) => ipcRenderer.invoke('stack:profile', opts),
  panel: (id, opts = {}) => ipcRenderer.invoke('panel:load', { id, ...opts }),
  cachedPanel: (id, envId) => ipcRenderer.invoke('panel:cached', envId == null ? { id } : { id, envId }),   // cached model (or, with envId, another client's Overview summary) or null; never calls Liongard
  refreshAll: () => ipcRenderer.invoke('client:refreshAll'),
  metricItems: o => ipcRenderer.invoke('metric:items', o),
  icons: () => ipcRenderer.invoke('icons:get'),
  setActionStatus: o => ipcRenderer.invoke('actions:setStatus', o),
  setComplianceMark: o => ipcRenderer.invoke('compliance:mark', o),
  setComplianceProfile: p => ipcRenderer.invoke('compliance:profile', p),
  addRemediation: items => ipcRenderer.invoke('remediation:add', items),
  updateRemediation: o => ipcRenderer.invoke('remediation:update', o),
  onRefreshProgress: fn => { const h = (_e, p) => fn(p); ipcRenderer.on('client:progress', h); return () => ipcRenderer.removeListener('client:progress', h); },
  exportHtml: html => ipcRenderer.invoke('export:html', html),
  setMsp: m => ipcRenderer.invoke('msp:set', m),
  setCoveragePolicy: p => ipcRenderer.invoke('coverage:policy', p),
  exportPdf: o => ipcRenderer.invoke('export:pdf', o),
  exportFile: o => ipcRenderer.invoke('export:file', o),
  exportCsv: o => ipcRenderer.invoke('export:csv', o),
});
